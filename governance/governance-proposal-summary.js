(function () {
    function createProposalSummaryModule({
        createCatalystContext,
        createGovernanceContext,
        createOverlay,
        fetchJson,
        removeOverlay
    }) {
        function translate(text) {
            return window.TDSPI18n?.translateText?.(text) || text;
        }

        function setTranslatedText(element, text) {
            if (!(element instanceof HTMLElement)) return;
            const value = String(text || '');
            element.setAttribute('data-i18n-auto', '');
            element.setAttribute('data-i18n-auto-original', value);
            element.textContent = translate(value);
        }

        function open({
            proposal,
            returnFocus,
            apiUrl,
            headerMeta,
            rootTitle,
            showClose
        }) {
            const content = document.createElement('div');
            content.className = 'governance-proposal-summary governance-menu-card';
            renderMessage(content, 'Loading AI summary...');

            createOverlay({
                id: 'governance-proposal-summary-overlay',
                titleId: 'governance-proposal-summary-title',
                titleText: 'Proposal Summary',
                closeLabel: 'Close proposal summary',
                closeOverlay: close,
                bodyNodes: [content],
                headerMeta,
                overlayClass: 'governance-action-detail-overlay',
                returnFocus,
                rootTitle,
                showClose,
                botContext: proposal?.proposal_id
                    ? createGovernanceContext(proposal)
                    : proposal?.id
                        ? createCatalystContext(proposal)
                        : undefined
            });

            load(apiUrl, content).catch(() => {
                if (!content.isConnected) return;
                renderMessage(content, 'The AI summary could not be loaded.');
            });
        }

        function close() {
            removeOverlay('governance-proposal-summary-overlay');
        }

        async function load(apiUrl, container, attempt = 0) {
            const payload = await fetchJson(apiUrl);
            if (!container.isConnected) return;

            if (payload?.status === 'pending') {
                renderMessage(container, 'This summary is being generated by the local AI...');
                if (attempt < 24) {
                    window.setTimeout(() => {
                        if (!container.isConnected) return;
                        load(apiUrl, container, attempt + 1).catch(() => {});
                    }, 5000);
                }
                return;
            }

            container.replaceChildren();
            const summarySections = [
                ['who_is_asking', 'Who is asking?'],
                ['amount_requested', 'How much are they asking?'],
                ['building_or_solving', 'What are they building or solving?'],
                ['approach', 'How will they do this?'],
                ['cardano_or_treasury_benefit', 'What will this bring Cardano and/or the Treasury?']
            ];
            if (payload?.sections && typeof payload.sections === 'object') {
                const summary = document.createElement('div');
                summary.className = 'governance-proposal-summary-sections';
                summarySections.forEach(([key, heading]) => {
                    const section = document.createElement('section');
                    section.className = 'governance-proposal-summary-section';
                    const title = document.createElement('h3');
                    setTranslatedText(title, heading);
                    const text = document.createElement('p');
                    text.textContent = payload.sections[key] || translate('Not stated in the proposal.');
                    section.append(title, text);
                    summary.appendChild(section);
                });
                container.appendChild(summary);
            } else {
                const summary = document.createElement('p');
                summary.className = 'governance-proposal-summary-text';
                summary.textContent = payload?.summary || translate('No summary is available.');
                container.appendChild(summary);
            }

            const warning = document.createElement('p');
            warning.className = 'small-text governance-proposal-summary-warning';
            setTranslatedText(warning, payload?.status === 'stale'
                ? '!! AI-generated summary based on an older proposal version. Verify it against the full proposal. !!'
                : '!! AI-generated summary. Verify important details against the full proposal before making decisions. !!');
            container.appendChild(warning);
        }

        function renderMessage(container, message) {
            container.replaceChildren();
            const status = document.createElement('p');
            status.className = 'small-text';
            setTranslatedText(status, message);
            container.appendChild(status);
        }

        return Object.freeze({
            close,
            open
        });
    }

    window.TDSPProposalSummary = Object.freeze({
        create: createProposalSummaryModule
    });
}());
